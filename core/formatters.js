/**
 * Unxnow Cookie Formatters & Parsers
 * Supports JSON, Header String, and Netscape formats
 */

export class JSONFormatter {
  /**
   * Parses JSON string into an array of cookie objects
   * @param {string} text
   * @returns {Array<object>}
   */
  static parse(text) {
    const data = JSON.parse(text);
    const cookies = Array.isArray(data) ? data : [data];
    return cookies.map((c) => ({
      name: c.name || '',
      value: c.value || '',
      domain: c.domain || '',
      path: c.path || '/',
      secure: Boolean(c.secure),
      httpOnly: Boolean(c.httpOnly),
      hostOnly: Boolean(c.hostOnly),
      session: Boolean(c.session || !c.expirationDate),
      expirationDate: c.expirationDate || null,
      sameSite: c.sameSite || 'lax'
    }));
  }

  /**
   * Formats cookie objects into pretty JSON string
   * @param {Array<object>} cookies
   * @returns {string}
   */
  static format(cookies) {
    const list = cookies.map((c) => ({
      name: c.name,
      value: c.value,
      domain: c.domain,
      path: c.path,
      secure: c.secure,
      httpOnly: c.httpOnly,
      hostOnly: c.hostOnly,
      session: c.session,
      expirationDate: c.expirationDate || null,
      sameSite: c.sameSite === 'unspecified' ? null : c.sameSite
    }));
    return JSON.stringify(list, null, 2);
  }
}

export class HeaderStringFormatter {
  /**
   * Parses HTTP Cookie header string (e.g., "id=123; user=john")
   * @param {string} text
   * @returns {Array<object>}
   */
  static parse(text) {
    const cookies = [];
    const pairs = text.split(';');

    for (let pair of pairs) {
      pair = pair.trim();
      if (!pair) continue;

      const eqPos = pair.indexOf('=');
      if (eqPos === -1) continue;

      const name = pair.substring(0, eqPos).trim();
      const value = pair.substring(eqPos + 1).trim();

      if (name) {
        cookies.push({
          name,
          value,
          path: '/',
          session: true,
          sameSite: 'lax'
        });
      }
    }

    if (cookies.length === 0) {
      throw new Error('No valid name=value pairs found in Header String.');
    }

    return cookies;
  }

  /**
   * Formats cookie objects into HTTP Cookie header string
   * @param {Array<object>} cookies
   * @returns {string}
   */
  static format(cookies) {
    return cookies.map((c) => `${c.name}=${c.value}`).join('; ');
  }
}

export class NetscapeFormatter {
  static HTTP_ONLY_PREFIX = '#HttpOnly_';

  /**
   * Parses Netscape HTTP Cookie File format (curl / wget format)
   * @param {string} text
   * @returns {Array<object>}
   */
  static parse(text) {
    const cookies = [];
    const lines = text.split('\n');

    for (let rawLine of lines) {
      let line = rawLine.trim();
      if (!line) continue;

      let isHttpOnly = false;
      if (line.startsWith(this.HTTP_ONLY_PREFIX)) {
        isHttpOnly = true;
        line = line.substring(this.HTTP_ONLY_PREFIX.length);
      }

      if (line.startsWith('#')) {
        continue; // Comment line
      }

      const parts = line.split('\t');
      if (parts.length < 7) {
        continue;
      }

      const [domain, subdomains, path, secure, expiration, name, value] = parts;
      const expNumber = parseInt(expiration, 10);
      const isSession = !expNumber || expNumber <= 0;

      cookies.push({
        domain: domain.trim(),
        hostOnly: subdomains.trim().toLowerCase() === 'false',
        path: path.trim() || '/',
        secure: secure.trim().toLowerCase() === 'true',
        expirationDate: isSession ? null : expNumber,
        session: isSession,
        name: name.trim(),
        value: value !== undefined ? value : '',
        httpOnly: isHttpOnly,
        sameSite: 'lax'
      });
    }

    if (cookies.length === 0) {
      throw new Error('No valid Netscape formatted cookies found.');
    }

    return cookies;
  }

  /**
   * Formats cookie objects into Netscape HTTP Cookie File format
   * @param {Array<object>} cookies
   * @returns {string}
   */
  static format(cookies) {
    let output = '# Netscape HTTP Cookie File\n# Generated by Unxnow Cookie Editor\n\n';

    for (const c of cookies) {
      const httpOnlyPrefix = c.httpOnly ? this.HTTP_ONLY_PREFIX : '';
      const domain = c.domain || '';
      const flag = c.hostOnly ? 'FALSE' : 'TRUE';
      const path = c.path || '/';
      const secure = c.secure ? 'TRUE' : 'FALSE';
      let expiration = 0;

      if (c.session) {
        // Netscape doesn't natively have session cookies, default 1 day TTL
        expiration = Math.round(Date.now() / 1000 + 86400);
      } else if (c.expirationDate) {
        expiration = Math.round(c.expirationDate);
      }

      output += `${httpOnlyPrefix}${domain}\t${flag}\t${path}\t${secure}\t${expiration}\t${c.name}\t${c.value}\n`;
    }

    return output;
  }
}

/**
 * Auto-detects format and parses input string into cookie objects
 * @param {string} text
 * @returns {Array<object>}
 */
export function autoDetectAndParse(text) {
  const trimmed = text.trim();
  if (!trimmed) {
    throw new Error('Input text is empty.');
  }

  // 1. Try JSON
  if (trimmed.startsWith('[') || trimmed.startsWith('{')) {
    try {
      return JSONFormatter.parse(trimmed);
    } catch {
      // Fall through
    }
  }

  // 2. Try Netscape
  if (trimmed.includes('# Netscape') || trimmed.includes('\t')) {
    try {
      return NetscapeFormatter.parse(trimmed);
    } catch {
      // Fall through
    }
  }

  // 3. Try Header String
  try {
    return HeaderStringFormatter.parse(trimmed);
  } catch {
    // Fall through
  }

  // Fallback try JSON one more time
  try {
    return JSONFormatter.parse(trimmed);
  } catch (err) {
    throw new Error('Unable to parse cookie data. Supported formats: JSON, Header String (name=val; ...), or Netscape.');
  }
}
